/**
 * Local Monaco setup — no CDN.
 *
 * By default @monaco-editor/react downloads Monaco from cdn.jsdelivr.net at
 * runtime. That breaks the "nothing leaves your machine" promise, fails on
 * air-gapped networks, and is blocked by our CSP (script-src 'self'). Here we
 * bundle Monaco from node_modules and hand it to the React wrapper.
 *
 * Slim build: all editor contributions (find, folding, multi-cursor, …) but
 * only the languages this app maps formats to, and no TypeScript/CSS/HTML
 * language services or LSP client — syntax highlighting is all we need.
 *
 * The contribution list mirrors monaco-editor/esm/vs/editor/editor.main.js;
 * regenerate it when upgrading monaco-editor.
 */
